export const SHAPES = {};
RANKS.forEach((rank) => {
  SHAPES[rank] = {};
  JOBS.forEach((job, ji) => {
    const list = LIB[rank] || LIB.B;
    SHAPES[rank][job] = (list[ji % list.length] || list[0]).map((c) => ({ ...c }));
  });
});

export function rotateShape(cells, rotation) {
  if (!rotation || rotation === 0) return cells.map((c) => ({ ...c }));
  let out = cells.map((c) => ({ ...c }));
  const times = (rotation / 90) % 4;
  for (let t = 0; t < times; t++) {
    const minX = Math.min(...out.map((c) => c.y));
    const minY = Math.min(...out.map((c) => -c.x));
    out = out.map(({ x, y }) => ({ x: y - minX, y: -x - minY }));
  }
  return out;
}
